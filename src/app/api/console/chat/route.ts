/**
 * Get a user's API key for any AI service from their Vault.
 */
async function getUserAIKey(userId: string, serviceName: string): Promise<string | null> {
  try {
    const admin = getAdmin()
    const { data: row } = await admin
      .from('user_vaults')
      .select('encrypted_key, iv, salt')
      .eq('user_id', userId)
      .eq('service_name', serviceName)
      .maybeSingle()

    if (!row?.encrypted_key || !row?.iv || !row?.salt) return null

    const plaintext = await decryptVaultData(userId, row.encrypted_key, row.iv, row.salt)
    try {
      const parsed = JSON.parse(plaintext)
      return parsed.api_key || null
    } catch {
      return plaintext || null
    }
  } catch {
    return null
  }
}

/**
 * Call Anthropic (Claude) API.
 */
async function callClaude(apiKey: string, message: string, source: AISource = 'claude-byok'): Promise<{ text: string; source: AISource } | null> {
  try {
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: 'claude-sonnet-4-20250514',
        max_tokens: 2048,
        system: SYSTEM_PROMPT,
        messages: [{ role: 'user', content: message }],
      }),
      signal: AbortSignal.timeout(30000),
    })

    if (!res.ok) {
      const errBody = await res.text().catch(() => '')
      console.error(`[chat-byok] Claude ${res.status}: ${errBody.slice(0, 500)}`)
      return null
    }

    const data = await res.json()
    const text = data.content?.[0]?.type === 'text'
      ? data.content[0].text
      : null

    return text ? { text, source } : null
  } catch (err) {
    console.error('[chat-byok] Claude error:', err instanceof Error ? err.message : err)
    return null
  }
}

/**
 * Call Groq API (FREE — primary fallback for all users).
 * Uses system GROQ_API_KEYS pool with round-robin rotation.
 */
async function callGroq(message: string, knowledgeContext: string = ''): Promise<{ text: string; source: AISource } | null> {
  try {
    const pool = (process.env.GROQ_API_KEYS || process.env.GROQ_API_KEY || '').split(',').filter(Boolean)
    if (pool.length === 0) return null
    const key = pool[Math.floor(Math.random() * pool.length)]

    const res = await fetch('https://api.groq.com/openai/v1/chat/completions', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${key.trim()}` },
      body: JSON.stringify({
        model: 'llama-3.3-70b-versatile',
        max_tokens: 2048,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT + (knowledgeContext ? '\n\n' + knowledgeContext : '') },
          { role: 'user', content: message },
        ],
      }),
      signal: AbortSignal.timeout(30000),
    })

    if (!res.ok) return null
    const data = await res.json()
    const text = data.choices?.[0]?.message?.content
    return text ? { text, source: 'groq-system' as AISource } : null
  } catch {
    return null
  }
}


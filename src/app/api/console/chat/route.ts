function getLocalResponse(message: string): string | null {
  const lower = message.toLowerCase().trim()

  // Direct keyword matches
  for (const [key, response] of Object.entries(LOCAL_KNOWLEDGE)) {
    if (lower.includes(key)) return response
  }

  // Pattern matches
  if (lower.match(/^(hi|hello|hey|yo|sup)/)) {
    return 'Hey! I\'m the 0n Console AI. I can help you with workflow automation, service connections, and cold email campaigns.\n\nTry:\n- `/smartlead` — Manage cold email campaigns\n- `/vault` — Connect your API keys\n- `/builder` — Build visual workflows\n- `/store` — Browse automation templates\n\nOr just describe what you want to automate.'
  }

  if (lower.match(/what (can you|do you|are you)/)) {
    return LOCAL_KNOWLEDGE['help']!
  }

  if (lower.match(/how (do i|to|can i).*(connect|add|setup|configure)/)) {
    return '**Connecting a Service**\n\n1. Go to **Vault** (`/vault`)\n2. Find the service you want to connect\n3. Click it and enter your API key/credentials\n4. Your key is encrypted and stored securely\n\nOnce connected, the service is available in the Builder, Chat, and all automations.'
  }

  if (lower.match(/how (do i|to|can i).*(create|build|make).*(workflow|automation|flow)/)) {
    return '**Creating a Workflow**\n\n**Option 1 — Visual Builder** (`/builder`)\n- Drag services from the palette onto the canvas\n- Connect nodes to define data flow\n- Configure each step\'s inputs and outputs\n\n**Option 2 — AI Create** (`/flows`)\n- Describe what you want in natural language\n- AI generates the .0n SWITCH file\n\n**Option 3 — Store Templates** (`/store`)\n- Browse pre-built automations\n- Import directly to your Builder'
  }

  if (lower.match(/(cold email|outreach|campaign|lead gen)/)) {
    return LOCAL_KNOWLEDGE['smartlead']!
  }

  if (lower.match(/(price|cost|pricing|plan|upgrade|pro|team|subscription)/)) {
    return '**0n Console Plans**\n\n- **Free** — Console access, Vault, Builder, Community\n- **Pro ($19/mo)** — Priority AI, advanced workflows, premium templates\n- **Team ($49/mo)** — Multi-user, team Vault, priority support, all features\n\nAll plans include a 7-day free trial. Upgrade via the Upgrade button in the header.'
  }

  // No match — return null to signal "use AI or generic fallback"
  return null
}

export async function POST(request: NextRequest) {
  // Verify auth
  const supabase = await createSupabaseServer()
  if (!supabase) {
    return NextResponse.json({ error: 'Auth not configured' }, { status: 500 })
  }

  const {
    data: { user },
  } = await supabase.auth.getUser()

  if (!user) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  }

  let body: {
    message?: string
    context?: {
      currentPage?: string
      brainSummary?: string
      preferences?: Record<string, unknown>
      learningTopics?: string[]
      missingServices?: string[]
      source?: 'console' | 'oncall'
    }
  }
  try {
    body = await request.json()
  } catch {
    return NextResponse.json({ error: 'Invalid JSON body' }, { status: 400 })
  }

  const message = body.message?.trim()
  if (!message) {
    return NextResponse.json({ error: 'Message is required' }, { status: 400 })
  }

  // ── Build context-enhanced message for AI layers ──────────
  let enhancedMessage = message
  if (body.context) {
    const ctx = body.context
    const parts: string[] = []
    if (ctx.currentPage) parts.push(`[User is on page: ${ctx.currentPage}]`)
    if (ctx.brainSummary) parts.push(`[Context: ${ctx.brainSummary}]`)
    if (ctx.missingServices?.length) parts.push(`[Missing services: ${ctx.missingServices.join(', ')}]`)
    if (ctx.learningTopics?.length) parts.push(`[Interested in: ${ctx.learningTopics.join(', ')}]`)
    if (parts.length > 0) {
      enhancedMessage = parts.join(' ') + '\n\n' + message
    }
  }

  // ── Inject location knowledge base (personal AI per sub-account) ──
  const locationKB = await getLocationKnowledge(user.id)
  if (locationKB) {
    enhancedMessage = locationKB + '\n\n' + enhancedMessage
  }

  // ── Inject service knowledge for mentioned services ────────
  const knowledgeContext = await getServiceKnowledge(message)
  if (knowledgeContext) {
    enhancedMessage = enhancedMessage + knowledgeContext
  }

  // ── Inject council knowledge (Brain training data) ────────
  const councilContext = await getCouncilKnowledge(message)
  if (councilContext) {
    enhancedMessage = enhancedMessage + councilContext
  }

  // ── Layer 1: Try 0nMCP local server ────────────────────────
  try {
    const mcpRes = await fetch(`${ONMCP_URL}/execute`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ task: message }),
      signal: AbortSignal.timeout(5000), // Quick timeout — don't hang
    })

    if (mcpRes.ok) {
      const data = await mcpRes.json()
      console.log('[chat] Layer 1 (0nMCP) succeeded')
      return NextResponse.json({
        text: data.result || data.output || data.message || 'Task executed successfully.',
        source: '0nmcp' as const,
        status: data.status || 'completed',
        steps: data.steps_executed || data.steps || 0,
        services: data.services_used || data.services || [],
      })
    }
    console.log(`[chat] Layer 1 (0nMCP) ${mcpRes.status} — skipping`)
  } catch (err) {
    console.log('[chat] Layer 1 (0nMCP) offline:', err instanceof Error ? err.message : 'connection refused')
  }

  // ── Layer 1.5: CRM Agent Studio (Knowledge Base + MCP) ──────
  if (process.env.CRM_AGENT_STUDIO_KEY) {
    try {
      console.log('[chat] Layer 1.5 (Agent Studio) — attempting...')
      const crmAccount = await getOrCreateCrmAccount(user.id)
      const agentId = crmAccount?.default_agent_id || process.env.CRM_AGENT_STUDIO_AGENT_ID || ''
      const locationId = crmAccount?.location_id || process.env.CRM_AGENT_STUDIO_LOCATION_ID || ''

      if (agentId && locationId) {
        const existingSession = await getActiveSession(user.id, agentId).catch(() => null)

        const agentResult = await executeAgent(agentId, {
          message: enhancedMessage,
          locationId,
          executionId: existingSession || undefined,
          inputVariables: {
            userId: user.id,
            userEmail: user.email || '',
          },
        })

        if (agentResult.text && !agentResult.error) {
          if (agentResult.executionId) {
            upsertSession({ userId: user.id, executionId: agentResult.executionId, agentId, locationId }).catch(() => {})
          }
          incrementExecutionCount(user.id).catch(() => {})

          console.log('[chat] Layer 1.5 (Agent Studio) succeeded')
          return NextResponse.json({
            text: agentResult.text,
            source: 'agent-studio' as AISource,
            status: 'completed',
            executionId: agentResult.executionId,
          })
        }
        console.log('[chat] Layer 1.5 (Agent Studio) returned empty/error:', agentResult.error || 'no text')
      } else {
        console.log('[chat] Layer 1.5 skipped — no agentId or locationId')
      }
    } catch (err) {
      console.error('[chat] Layer 1.5 (Agent Studio) error:', err instanceof Error ? err.message : err)
    }
  } else {
    console.log('[chat] Layer 1.5 skipped — no CRM_AGENT_STUDIO_KEY')
  }

  // ── Layer 2: User's own AI key (BYOK — Claude, GPT, or Gemini) ──
  let byokOrder: AIProvider[] = [...AI_SERVICES]
  try {
    const admin = getAdmin()
    const { data: profile } = await admin
      .from('profiles')
      .select('core_ai_provider')
      .eq('id', user.id)
      .maybeSingle()
    const coreProvider = profile?.core_ai_provider as AIProvider | null
    if (coreProvider && AI_SERVICES.includes(coreProvider)) {
      byokOrder = [coreProvider, ...AI_SERVICES.filter(p => p !== coreProvider)]
    }
  } catch { /* continue with default order */ }

  console.log(`[chat] Layer 2 (BYOK) order: ${byokOrder.join(' → ')}`)
  for (const provider of byokOrder) {
    const userKey = await getUserAIKey(user.id, provider)
    if (!userKey) continue

    console.log(`[chat] Layer 2: trying BYOK ${provider}...`)
    let result: { text: string; source: AISource } | null = null
    if (provider === 'anthropic') {
      result = await callClaude(userKey, enhancedMessage, 'claude-byok')
    } else if (provider === 'openai') {
      result = await callOpenAI(userKey, enhancedMessage)
    } else if (provider === 'google') {
      result = await callGemini(userKey, enhancedMessage)
    } else if (provider === 'openrouter') {
      result = await callOpenRouterChat(userKey, enhancedMessage)
    }

    if (result) {
      console.log(`[chat] Layer 2: BYOK ${provider} succeeded`)
      return NextResponse.json({
        text: result.text,
        source: result.source,
      })
    }
    console.log(`[chat] Layer 2: BYOK ${provider} failed`)
  }
  console.log('[chat] Layer 2 (BYOK) — no user keys found or all failed')

  // ── Layer 3: Platform keys — all 10 providers, ordered by user preference ──
  const providerOrder = await resolveProviderOrder(user.id)

  console.log(`[chat] Layer 3 (Platform keys) order: ${providerOrder.join(' → ')}`)
  console.log(`[chat] Layer 3 keys present: ${providerOrder.map(p => `${p}=${getProviderKey(p) ? 'YES' : 'NO'}`).join(', ')}`)

  for (const provider of providerOrder) {
    const key = getProviderKey(provider)
    if (!key) continue

    console.log(`[chat] Layer 3: trying ${provider} (${key.slice(0, 8)}...)`)
    const text = await callProvider(provider, key, {
      system: SYSTEM_PROMPT,
      user: enhancedMessage,
      maxTokens: 2048,
    })
    if (text) {
      console.log(`[chat] Layer 3: ${provider} succeeded`)
      return NextResponse.json({
        text,
        source: provider as AISource,
      })
    }
    console.log(`[chat] Layer 3: ${provider} failed — next`)
  }
  console.error('[chat] Layer 3 — ALL 10 platform providers failed')

  // ── Layer 5: System Groq (FREE — always available) ──────────
  console.log('[chat] Layer 5: Trying system Groq (free)')
  const groqResult = await callGroq(enhancedMessage, knowledgeContext)
  if (groqResult) {
    return NextResponse.json(groqResult)
  }
  console.log('[chat] Layer 5: Groq failed')

  // ── Layer 6: Smart local fallback ──────────────────────────
  const localResponse = getLocalResponse(message)
  if (localResponse) {
    return NextResponse.json({
      text: localResponse,
      source: 'local' as const,
    })
  }

  // ── Layer 7: Generic helpful response ──────────────────────
  return NextResponse.json({
    text: '**I can help with that!** To unlock full AI-powered responses, connect an API key in the **Vault** — Claude, GPT-4o, or Gemini.\n\n' +
      'In the meantime, try these commands:\n' +
      '- `/vault` — Connect services\n' +
      '- `/builder` — Visual workflow builder\n' +
      '- `/store` — Browse automation templates\n' +
      '- `/help` — See all available commands',
    source: 'local' as const,
  })
}
